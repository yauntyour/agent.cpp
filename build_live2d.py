#!/usr/bin/env python3
"""把 assets/live2d/ 里的默认模型打进 exe。

    assets/live2d/models/**      自带的默认模型（Live2D 运行时核心不在这里：
                                 Cubism Core 由用户自己下载，见面板里的「下载运行时」）

产物：

    src/agent-live2d.hpp    一张 #embed 表（C++26）；启动时按需写进 .agent/live2d/，
                            已经有模型的话一个字节都不动。

编译器不支持 `#embed`（GCC < 15 / Clang < 19）时产物里 kAssetCount = 0：
程序照常启动，只是没有自带模型，舞台会提示去面板里选一个。

用法：
    python build_live2d.py            # 生成 src/agent-live2d.hpp
    python build_live2d.py --check    # 产物过期则失败
"""
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent
SRC = ROOT / "assets/live2d"
OUT = ROOT / "src/agent-live2d.hpp"
# 生成的 header 放在 src/ 下，所以 #embed 的路径是相对 src/ 的
REL = "../assets/live2d"

BANNER = """// agent-live2d.hpp — GENERATED by build_live2d.py from assets/live2d/.
// Do not edit by hand: edit the files under assets/live2d/ and re-run
//   python build_live2d.py        (the CMake build does it)
"""


def collect() -> list[pathlib.Path]:
    if not SRC.is_dir():
        raise SystemExit(f"build_live2d: {SRC} not found")
    files = []
    for p in sorted(SRC.rglob("*")):
        if not p.is_file():
            continue
        # 顶层说明文件不进 exe（不参与运行时，只解释许可）
        if p.parent == SRC and p.suffix.lower() in {".md", ".txt"}:
            continue
        if p.stat().st_size == 0:
            raise SystemExit(f"build_live2d: empty file {p.relative_to(ROOT)}")
        files.append(p)
    if not files:
        raise SystemExit(f"build_live2d: no files under {SRC}")
    return files


def build(files: list[pathlib.Path]) -> str:
    rows = []
    for i, p in enumerate(files):
        rows.append((f"kA{i}", p.relative_to(SRC).as_posix(), f"{REL}/{p.relative_to(SRC).as_posix()}"))

    out = [BANNER]
    out.append("#pragma once\n\n#include <cstddef>\n\nnamespace app::stage\n{\n")
    # 只探测一次：能 #embed 一个文件，就能 #embed 所有文件
    out.append("#if defined(__has_embed)\n")
    out.append(f'#if __has_embed("{rows[0][2]}") == 1\n')
    out.append("#define AGENT_EMBED_LIVE2D 1\n")
    out.append("#endif\n#endif\n\n")
    out.append("    struct asset\n    {\n"
               "        const char *path; // 相对 .agent/live2d/\n"
               "        const unsigned char *data;\n"
               "        std::size_t size;\n"
               "    };\n\n")
    out.append("#ifdef AGENT_EMBED_LIVE2D\n")
    for var, _, rel in rows:
        out.append(f"    inline const unsigned char {var}[] = {{\n")
        out.append(f'#embed "{rel}"\n')
        out.append("    };\n")
    out.append("\n    inline const asset kAssets[] = {\n")
    for var, path, _ in rows:
        out.append(f'        {{"{path}", {var}, sizeof({var})}},\n')
    out.append("    };\n")
    out.append(f"    inline constexpr std::size_t kAssetCount = {len(rows)};\n")
    out.append("#else\n"
               "    inline const asset *const kAssets = nullptr;\n"
               "    inline constexpr std::size_t kAssetCount = 0;\n"
               "#endif\n")
    out.append("} // namespace app::stage\n")
    return "".join(out)


def save(path: pathlib.Path, text: str) -> None:
    if path.is_file() and path.read_text(encoding="utf-8") == text:
        print(f"build_live2d: untouched {path.relative_to(ROOT)}")
        return
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"build_live2d: -> {path.relative_to(ROOT)}")


def main() -> int:
    page = build(collect())
    if "--check" in sys.argv[1:]:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8") != page:
            print(f"build_live2d: stale {OUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
        print("build_live2d: up to date")
        return 0
    save(OUT, page)
    return 0


if __name__ == "__main__":
    sys.exit(main())
